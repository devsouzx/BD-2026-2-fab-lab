-- Função auxiliar: diferença em minutos inteiros entre dois instantes
CREATE OR REPLACE FUNCTION minutos_entre(p_inicio TIMESTAMP, p_fim TIMESTAMP)
RETURNS INTEGER AS $$
    SELECT CAST(FLOOR(EXTRACT(EPOCH FROM (p_fim - p_inicio)) / 60) AS INTEGER);
$$ LANGUAGE SQL IMMUTABLE;

-- ---------------------------------------------------------------------
-- A) Exigência do enunciado: data_inclusao e data_alteracao
--    Tabelas escolhidas: USUARIO e EQUIPAMENTO
--    INSERT -> grava a data atual em data_inclusao
--    UPDATE -> grava a data atual em data_alteracao
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_data_inclusao() RETURNS TRIGGER AS $$
BEGIN
    NEW.data_inclusao := NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION fn_data_alteracao() RETURNS TRIGGER AS $$
BEGIN
    NEW.data_alteracao := NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_usuario_bi BEFORE INSERT ON usuario
    FOR EACH ROW EXECUTE FUNCTION fn_data_inclusao();
CREATE TRIGGER trg_usuario_bu BEFORE UPDATE ON usuario
    FOR EACH ROW EXECUTE FUNCTION fn_data_alteracao();

CREATE TRIGGER trg_equipamento_bi BEFORE INSERT ON equipamento
    FOR EACH ROW EXECUTE FUNCTION fn_data_inclusao();
CREATE TRIGGER trg_equipamento_bu BEFORE UPDATE ON equipamento
    FOR EACH ROW EXECUTE FUNCTION fn_data_alteracao();

-- ---------------------------------------------------------------------
-- B) Regras de negócio dos requisitos
--    RF07 - impedir reserva/utilização por usuário sem autorização
--    RF10 - impedir reservas sobrepostas para o mesmo equipamento
--    RF11 - impedir reserva em período de manutenção
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_valida_reserva() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.status = 'Cancelada' THEN
        RETURN NEW;
    END IF;

    -- RF07
    IF (SELECT requer_autorizacao FROM equipamento
         WHERE id_equipamento = NEW.id_equipamento)
       AND NOT EXISTS (SELECT 1 FROM autorizacao
                        WHERE id_usuario = NEW.id_usuario
                          AND id_equipamento = NEW.id_equipamento) THEN
        RAISE EXCEPTION 'RF07: usuário sem autorização para este equipamento.';
    END IF;

    -- RF10
    IF EXISTS (SELECT 1 FROM reserva r
                WHERE r.id_equipamento = NEW.id_equipamento
                  AND r.id_reserva <> NEW.id_reserva
                  AND r.status <> 'Cancelada'
                  AND NEW.data_hora_inicio < r.data_hora_fim
                  AND NEW.data_hora_fim    > r.data_hora_inicio) THEN
        RAISE EXCEPTION 'RF10: já existe reserva para este equipamento no período.';
    END IF;

    -- RF11 (a) equipamento Indisponível ou Em manutenção não aceita nova reserva ativa
    IF NEW.status = 'Ativa'
       AND (SELECT status FROM equipamento
             WHERE id_equipamento = NEW.id_equipamento)
           IN ('Indisponível', 'Em manutenção') THEN
        RAISE EXCEPTION 'RF11: equipamento indisponível ou em manutenção não pode ser reservado.';
    END IF;

    -- RF11 (b) período coincide com manutenção registrada (sem data de fim = em andamento)
    IF EXISTS (SELECT 1 FROM manutencao m
                WHERE m.id_equipamento = NEW.id_equipamento
                  AND NEW.data_hora_inicio < COALESCE(m.data_hora_fim, 'infinity'::TIMESTAMP)
                  AND NEW.data_hora_fim    > m.data_hora_inicio) THEN
        RAISE EXCEPTION 'RF11: equipamento em manutenção no período solicitado.';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_reserva_biu BEFORE INSERT OR UPDATE ON reserva
    FOR EACH ROW EXECUTE FUNCTION fn_valida_reserva();

CREATE OR REPLACE FUNCTION fn_valida_utilizacao() RETURNS TRIGGER AS $$
BEGIN
    -- RF07 (utilização)
    IF (SELECT requer_autorizacao FROM equipamento
         WHERE id_equipamento = NEW.id_equipamento)
       AND NOT EXISTS (SELECT 1 FROM autorizacao
                        WHERE id_usuario = NEW.id_usuario
                          AND id_equipamento = NEW.id_equipamento) THEN
        RAISE EXCEPTION 'RF07: usuário sem autorização para utilizar este equipamento.';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_utilizacao_bi BEFORE INSERT ON utilizacao
    FOR EACH ROW EXECUTE FUNCTION fn_valida_utilizacao();
