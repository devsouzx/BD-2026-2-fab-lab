-- ---------------------------------------------------------------------
-- 1. USUARIO
-- (data_inclusao / data_alteracao: exigência do enunciado, preenchidas
--  por triggers - ver final do script)
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id_usuario      INT          GENERATED BY DEFAULT AS IDENTITY,
    nome            VARCHAR(100) NOT NULL,
    email           VARCHAR(100) NOT NULL,
    perfil          VARCHAR(30)  NOT NULL,
    telefone        VARCHAR(20)  NULL,
    data_inclusao   TIMESTAMP    NULL,
    data_alteracao  TIMESTAMP    NULL,
    CONSTRAINT pk_usuario       PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_email UNIQUE (email)
);

-- ---------------------------------------------------------------------
-- 2. EQUIPAMENTO
-- ---------------------------------------------------------------------
CREATE TABLE equipamento (
    id_equipamento      INT          GENERATED BY DEFAULT AS IDENTITY,
    nome                VARCHAR(100) NOT NULL,
    categoria           VARCHAR(50)  NOT NULL,
    descricao           VARCHAR(255) NULL,
    requer_autorizacao  BOOLEAN      NOT NULL DEFAULT FALSE,
    status              VARCHAR(20)  NOT NULL DEFAULT 'Disponível',
    data_inclusao       TIMESTAMP    NULL,
    data_alteracao      TIMESTAMP    NULL,
    CONSTRAINT pk_equipamento PRIMARY KEY (id_equipamento),
    CONSTRAINT ck_equipamento_status CHECK
        (status IN ('Disponível', 'Em utilização', 'Indisponível', 'Em manutenção'))
);

-- ---------------------------------------------------------------------
-- 3. PROJETO
-- ---------------------------------------------------------------------
CREATE TABLE projeto (
    id_projeto   INT          GENERATED BY DEFAULT AS IDENTITY,
    nome         VARCHAR(100) NOT NULL,
    descricao    VARCHAR(500) NULL,
    data_inicio  DATE         NOT NULL,
    data_fim     DATE         NULL,
    CONSTRAINT pk_projeto PRIMARY KEY (id_projeto),
    CONSTRAINT ck_projeto_datas CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

-- ---------------------------------------------------------------------
-- 4. MATERIAL
-- ---------------------------------------------------------------------
CREATE TABLE material (
    id_material            INT           GENERATED BY DEFAULT AS IDENTITY,
    nome                   VARCHAR(100)  NOT NULL,
    unidade_medida         VARCHAR(20)   NOT NULL,
    quantidade_disponivel  DECIMAL(10,2) NOT NULL DEFAULT 0,
    CONSTRAINT pk_material PRIMARY KEY (id_material),
    CONSTRAINT ck_material_qtd CHECK (quantidade_disponivel >= 0)
);

-- ---------------------------------------------------------------------
-- 5. AUTORIZACAO  (Usuario N:N Equipamento, com identificador próprio)
-- ---------------------------------------------------------------------
CREATE TABLE autorizacao (
    id_autorizacao    INT  GENERATED BY DEFAULT AS IDENTITY,
    id_usuario        INT  NOT NULL,
    id_equipamento    INT  NOT NULL,
    data_autorizacao  DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_autorizacao PRIMARY KEY (id_autorizacao),
    CONSTRAINT uq_autorizacao_usuario_equip UNIQUE (id_usuario, id_equipamento),
    CONSTRAINT fk_autorizacao_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_autorizacao_equipamento FOREIGN KEY (id_equipamento)
        REFERENCES equipamento (id_equipamento) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- 6. RESERVA
-- ---------------------------------------------------------------------
CREATE TABLE reserva (
    id_reserva        INT         GENERATED BY DEFAULT AS IDENTITY,
    id_usuario        INT         NOT NULL,
    id_equipamento    INT         NOT NULL,
    data_hora_inicio  TIMESTAMP   NOT NULL,
    data_hora_fim     TIMESTAMP   NOT NULL,
    status            VARCHAR(20) NOT NULL DEFAULT 'Ativa',
    CONSTRAINT pk_reserva PRIMARY KEY (id_reserva),
    CONSTRAINT ck_reserva_periodo CHECK (data_hora_fim > data_hora_inicio),
    CONSTRAINT fk_reserva_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_reserva_equipamento FOREIGN KEY (id_equipamento)
        REFERENCES equipamento (id_equipamento) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- 7. OCORRENCIA
-- ---------------------------------------------------------------------
CREATE TABLE ocorrencia (
    id_ocorrencia   INT          GENERATED BY DEFAULT AS IDENTITY,
    id_equipamento  INT          NOT NULL,
    data_hora       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    descricao       VARCHAR(500) NOT NULL,
    CONSTRAINT pk_ocorrencia PRIMARY KEY (id_ocorrencia),
    CONSTRAINT fk_ocorrencia_equipamento FOREIGN KEY (id_equipamento)
        REFERENCES equipamento (id_equipamento) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- 8. MANUTENCAO
-- ---------------------------------------------------------------------
CREATE TABLE manutencao (
    id_manutencao      INT          GENERATED BY DEFAULT AS IDENTITY,
    id_equipamento     INT          NOT NULL,
    data_hora_inicio   TIMESTAMP    NOT NULL,
    data_hora_fim      TIMESTAMP    NULL,
    descricao_servico  VARCHAR(500) NOT NULL,
    CONSTRAINT pk_manutencao PRIMARY KEY (id_manutencao),
    CONSTRAINT ck_manutencao_periodo CHECK
        (data_hora_fim IS NULL OR data_hora_fim >= data_hora_inicio),
    CONSTRAINT fk_manutencao_equipamento FOREIGN KEY (id_equipamento)
        REFERENCES equipamento (id_equipamento) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- 9. PARTICIPACAO  (Usuario N:N Projeto)
-- ---------------------------------------------------------------------
CREATE TABLE participacao (
    id_usuario   INT  NOT NULL,
    id_projeto   INT  NOT NULL,
    data_inicio  DATE NOT NULL,
    CONSTRAINT pk_participacao PRIMARY KEY (id_usuario, id_projeto),
    CONSTRAINT fk_participacao_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_participacao_projeto FOREIGN KEY (id_projeto)
        REFERENCES projeto (id_projeto) ON UPDATE CASCADE ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- 10. CONSUMO_MATERIAL  (Material N:N Projeto)
-- ---------------------------------------------------------------------
CREATE TABLE consumo_material (
    id_material  INT           NOT NULL,
    id_projeto   INT           NOT NULL,
    quantidade   DECIMAL(10,2) NOT NULL,
    CONSTRAINT pk_consumo_material PRIMARY KEY (id_material, id_projeto),
    CONSTRAINT ck_consumo_qtd CHECK (quantidade > 0),
    CONSTRAINT fk_consumo_material FOREIGN KEY (id_material)
        REFERENCES material (id_material) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_consumo_projeto FOREIGN KEY (id_projeto)
        REFERENCES projeto (id_projeto) ON UPDATE CASCADE ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- 11. PROJETO_EQUIPAMENTO  (Projeto N:N Equipamento)
-- ---------------------------------------------------------------------
CREATE TABLE projeto_equipamento (
    id_projeto      INT NOT NULL,
    id_equipamento  INT NOT NULL,
    CONSTRAINT pk_projeto_equipamento PRIMARY KEY (id_projeto, id_equipamento),
    CONSTRAINT fk_pe_projeto FOREIGN KEY (id_projeto)
        REFERENCES projeto (id_projeto) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_pe_equipamento FOREIGN KEY (id_equipamento)
        REFERENCES equipamento (id_equipamento) ON UPDATE CASCADE ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- 12. UTILIZACAO  (histórico de uso: Usuario N:N Equipamento)
-- ---------------------------------------------------------------------
CREATE TABLE utilizacao (
    id_usuario      INT       NOT NULL,
    id_equipamento  INT       NOT NULL,
    data_inicio     TIMESTAMP NOT NULL,
    data_fim        TIMESTAMP NULL,
    CONSTRAINT pk_utilizacao PRIMARY KEY (id_usuario, id_equipamento, data_inicio),
    CONSTRAINT ck_utilizacao_periodo CHECK (data_fim IS NULL OR data_fim >= data_inicio),
    CONSTRAINT fk_utilizacao_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_utilizacao_equipamento FOREIGN KEY (id_equipamento)
        REFERENCES equipamento (id_equipamento) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- 13. MANUTENCAO_OCORRENCIA  (Manutencao N:N Ocorrencia)
-- ---------------------------------------------------------------------
CREATE TABLE manutencao_ocorrencia (
    id_manutencao  INT NOT NULL,
    id_ocorrencia  INT NOT NULL,
    CONSTRAINT pk_manutencao_ocorrencia PRIMARY KEY (id_manutencao, id_ocorrencia),
    CONSTRAINT fk_mo_manutencao FOREIGN KEY (id_manutencao)
        REFERENCES manutencao (id_manutencao) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_mo_ocorrencia FOREIGN KEY (id_ocorrencia)
        REFERENCES ocorrencia (id_ocorrencia) ON UPDATE CASCADE ON DELETE CASCADE
